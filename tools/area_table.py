#!/usr/bin/env python3
"""Area table for the Phase II report from the Yosys 'stat' outputs.

Reads results/synth2/*_stat.txt (and the Phase I ROM measurement
results/synth/rom_stat.txt) and prints a markdown table plus report/data/area.tex
rows. Counting rules (Xilinx 7-series, same as Phase I):
  logic LUTs = LUT1..LUT6 + INV
  LUT-RAM    = 4 LUTs per RAM32M / RAM64M / RAM256X1S, 2 per RAM128X1S / RAM64X1D /
               RAM32X1D, 1 per RAM64X1S / RAM32X1S
  FFs        = FDRE + FDSE + FDCE + FDPE
Run from the repository root:  python3 tools/area_table.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAM_LUTS = {"RAM32M": 4, "RAM64M": 4, "RAM256X1S": 4, "RAM128X1S": 2, "RAM64X1D": 2,
            "RAM32X1D": 2, "RAM64X1S": 1, "RAM32X1S": 1, "RAM128X1D": 4}

DESIGNS = [
    ("harvard", "Ideal Harvard (core + data side, ROM separate)"),
    ("vn", "Ideal shared memory (Phase I baseline)"),
    ("mh", "Modified Harvard: I\\$ 8 + D\\$ 8 lines"),
    ("vnc_unified", "Single bus + unified cache, 16 lines"),
    ("vnc_nocache", "Single bus, no cache"),
    ("cache", "One cache on its own (8 lines, buffer)"),
]


def cells(path):
    c = {}
    with open(path) as f:
        for line in f:
            m = re.match(r"\s+(\d+)\s+(\S+)\s*$", line)
            if m and not m.group(2).startswith("$") and m.group(2) not in ("cells",):
                c[m.group(2)] = int(m.group(1))
    return c


def summary(c):
    logic = sum(v for k, v in c.items() if re.fullmatch(r"LUT[1-6]", k)) + c.get("INV", 0)
    ram = sum(RAM_LUTS[k] * v for k, v in c.items() if k in RAM_LUTS)
    ff = sum(c.get(k, 0) for k in ("FDRE", "FDSE", "FDCE", "FDPE"))
    return logic, ram, logic + ram, ff, c.get("CARRY4", 0), c.get("MUXF7", 0) + c.get("MUXF8", 0)


def main():
    rom = summary(cells(os.path.join(ROOT, "results", "synth", "rom_stat.txt")))
    rows = []
    for key, name in DESIGNS:
        s = summary(cells(os.path.join(ROOT, "results", "synth2", f"{key}_stat.txt")))
        if key == "harvard":
            s = tuple(a + b for a, b in zip(s, rom))   # add the separately measured ROM
            name = "Ideal Harvard (incl. 256-word ROM)"
        rows.append((key, name, s))
    print("# Phase II area (Yosys synth_xilinx -family xc7, generated by tools/area_table.py)\n")
    print("Shared lower-level memory (main_mem) is a black box in every cached design; the ideal "
          "designs contain their own memories as LUT-RAM. The Harvard ROM is the Phase I "
          "separate measurement (results/synth/rom_stat.txt).\n")
    print("| Design | Logic LUTs | LUT-RAM LUTs | Total LUTs | FFs | CARRY4 | MUXF7/8 |")
    print("|---|---|---|---|---|---|---|")
    for _, name, s in rows:
        print(f"| {name.replace(chr(92), '')} | " + " | ".join(str(x) for x in s) + " |")
    os.makedirs(os.path.join(ROOT, "report", "data"), exist_ok=True)
    with open(os.path.join(ROOT, "report", "data", "area.tex"), "w") as f:
        f.write("% generated by tools/area_table.py -- do not edit\n")
        for _, name, s in rows:
            f.write(f"{name} & {s[0]} & {s[1]} & {s[2]} & {s[3]} \\\\\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
